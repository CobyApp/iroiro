-- 회사 판매(product)와 별개의 유저 등록 매물. 고정가/경매 모두 지원하며
-- 경매 필드·CHECK는 product의 auction 패턴을 그대로 따른다.
-- 기능 전체가 site_setting.used_trade_enabled 플래그 뒤에 숨는다(런칭 전 OFF).

-- site_setting — 디자인 테마 제거로 삭제됐던 싱글턴을 범용 설정으로 재도입.
CREATE TABLE site_setting
(
    id                 BIGINT PRIMARY KEY,
    used_trade_enabled BOOLEAN     NOT NULL DEFAULT false,
    used_trade_fee_bp  INT         NOT NULL DEFAULT 1000,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE site_setting
    ADD CONSTRAINT site_setting_singleton CHECK (id = 1),
    ADD CONSTRAINT site_setting_fee_bp_chk CHECK (used_trade_fee_bp BETWEEN 0 AND 5000);

INSERT INTO site_setting (id) VALUES (1);

COMMENT ON TABLE site_setting IS '사이트 전역 설정 — 항상 1행(singleton, CHECK id=1)';
COMMENT ON COLUMN site_setting.id IS 'PK — 항상 1';
COMMENT ON COLUMN site_setting.used_trade_enabled IS '중고거래 기능 노출 여부 — OFF면 고객 화면에서 완전히 숨김';
COMMENT ON COLUMN site_setting.used_trade_fee_bp IS '중고거래 판매 수수료(만분율, 1000=10%). 0~5000';
COMMENT ON COLUMN site_setting.created_at IS '생성일';
COMMENT ON COLUMN site_setting.updated_at IS '수정일';

-- 중고 매물 — 유저가 직접 등록. 카탈로그(그룹→멤버→종류→시리즈) 참조는 선택.
CREATE TABLE used_listing
(
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_account_id         UUID        NOT NULL,
    item_type                 TEXT        NOT NULL DEFAULT 'photocard',
    team_id                   BIGINT,
    member_id                 BIGINT,
    series_id                 BIGINT,
    source_product_id         BIGINT,
    title                     TEXT        NOT NULL,
    description               TEXT,
    condition                 TEXT        NOT NULL,
    sale_mode                 TEXT        NOT NULL DEFAULT 'fixed',
    price                     INT,
    shipping_method           TEXT        NOT NULL DEFAULT 'post',
    shipping_fee              INT         NOT NULL DEFAULT 0,
    status                    TEXT        NOT NULL DEFAULT 'active',
    auction_start_price       INT,
    auction_current_price     INT,
    auction_bid_count         INT         NOT NULL DEFAULT 0,
    auction_ends_at           TIMESTAMPTZ,
    auction_status            TEXT,
    auction_winner_account_id UUID,
    auction_pay_due_at        TIMESTAMPTZ,
    view_count                INT         NOT NULL DEFAULT 0,
    created_at                TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at                TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE used_listing
    ADD CONSTRAINT used_listing_sale_mode_chk CHECK (sale_mode IN ('fixed', 'auction')),
    ADD CONSTRAINT used_listing_status_chk
        CHECK (status IN ('active', 'reserved', 'sold', 'canceled', 'blocked')),
    ADD CONSTRAINT used_listing_shipping_chk
        CHECK (shipping_method IN ('post', 'parcel', 'direct')),
    ADD CONSTRAINT used_listing_price_chk
        CHECK (sale_mode = 'auction' OR (price IS NOT NULL AND price > 0)),
    ADD CONSTRAINT used_listing_auction_fields_chk CHECK (
        sale_mode = 'fixed'
        OR (
            auction_start_price IS NOT NULL
            AND auction_start_price > 0
            AND auction_ends_at IS NOT NULL
            AND auction_status IS NOT NULL
        )
    ),
    ADD CONSTRAINT used_listing_auction_status_chk
        CHECK (auction_status IS NULL OR auction_status IN ('live', 'awarded', 'passed'));

CREATE INDEX used_listing_status_created_idx ON used_listing (status, created_at DESC);
CREATE INDEX used_listing_seller_idx ON used_listing (seller_account_id, created_at DESC);
CREATE INDEX used_listing_series_idx ON used_listing (series_id);
CREATE INDEX used_listing_member_idx ON used_listing (member_id);
CREATE INDEX used_listing_auction_due_idx
    ON used_listing (auction_status, auction_ends_at)
    WHERE sale_mode = 'auction';

