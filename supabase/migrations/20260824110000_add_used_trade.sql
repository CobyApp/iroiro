-- 매물 사진 — 유저 업로드(복수). 대표사진은 정확히 1장.
CREATE TABLE used_listing_photo
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id    BIGINT      NOT NULL,
    r2_key        TEXT        NOT NULL,
    display_order INT         NOT NULL DEFAULT 0,
    is_primary    BOOLEAN     NOT NULL DEFAULT false,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX used_listing_photo_primary_unique
    ON used_listing_photo (listing_id) WHERE (is_primary = true);
CREATE INDEX used_listing_photo_listing_idx ON used_listing_photo (listing_id, display_order);

COMMENT ON TABLE used_listing_photo IS '중고 매물 사진 — 유저 업로드';
COMMENT ON COLUMN used_listing_photo.id IS 'PK';
COMMENT ON COLUMN used_listing_photo.listing_id IS '매물 used_listing.id';
COMMENT ON COLUMN used_listing_photo.r2_key IS 'R2 객체 키';
COMMENT ON COLUMN used_listing_photo.display_order IS '노출 순서';
COMMENT ON COLUMN used_listing_photo.is_primary IS '대표사진 — 매물당 1장(부분 유니크)';
COMMENT ON COLUMN used_listing_photo.created_at IS '생성일';

-- 중고 경매 입찰 원장 — auction_bid와 동일 패턴(INSERT만).
CREATE TABLE used_bid
(
    id         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    listing_id BIGINT      NOT NULL,
    account_id UUID        NOT NULL,
    amount     INT         NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE used_bid
    ADD CONSTRAINT used_bid_amount_positive CHECK (amount > 0);

CREATE INDEX used_bid_listing_idx ON used_bid (listing_id, amount DESC, id ASC);
CREATE INDEX used_bid_account_idx ON used_bid (account_id, created_at DESC);

COMMENT ON TABLE used_bid IS '중고 경매 입찰 원장';
COMMENT ON COLUMN used_bid.id IS 'PK';
COMMENT ON COLUMN used_bid.listing_id IS '매물 used_listing.id';
COMMENT ON COLUMN used_bid.account_id IS '입찰자 account.id';
COMMENT ON COLUMN used_bid.amount IS '입찰가(KRW)';
COMMENT ON COLUMN used_bid.created_at IS '입찰 시각';

-- 중고 거래 — 구매 확정 시 1건. 수수료율은 거래 시점 스냅샷(설정 변경과 무관).
CREATE TABLE used_trade
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id         BIGINT      NOT NULL,
    buyer_account_id   UUID        NOT NULL,
    seller_account_id  UUID        NOT NULL,
    price              INT         NOT NULL,
    shipping_fee       INT         NOT NULL DEFAULT 0,
    fee_bp             INT         NOT NULL,
    fee_amount         INT         NOT NULL,
    seller_payout      INT         NOT NULL,
    status             TEXT        NOT NULL DEFAULT 'pending',
    recipient_name     TEXT,
    recipient_phone    TEXT,
    recipient_address  TEXT,
    post_tracking_code TEXT,
    post_qr_issued_at  TIMESTAMPTZ,
    completed_at       TIMESTAMPTZ,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE used_trade
    ADD CONSTRAINT used_trade_status_chk
        CHECK (status IN ('pending', 'paid', 'shipped', 'completed', 'canceled')),
    ADD CONSTRAINT used_trade_amounts_chk
        CHECK (price > 0 AND fee_amount >= 0 AND seller_payout >= 0);

CREATE UNIQUE INDEX used_trade_listing_unique ON used_trade (listing_id)
    WHERE (status <> 'canceled');
CREATE INDEX used_trade_buyer_idx ON used_trade (buyer_account_id, created_at DESC);
CREATE INDEX used_trade_seller_idx ON used_trade (seller_account_id, created_at DESC);
CREATE INDEX used_trade_status_idx ON used_trade (status, created_at DESC);

COMMENT ON TABLE used_trade IS '중고 거래 — 매물당 유효 거래 1건(취소 제외)';
COMMENT ON COLUMN used_trade.id IS 'PK';
COMMENT ON COLUMN used_trade.listing_id IS '매물 used_listing.id';
COMMENT ON COLUMN used_trade.buyer_account_id IS '구매자 account.id';
COMMENT ON COLUMN used_trade.seller_account_id IS '판매자 account.id (비정규화)';
COMMENT ON COLUMN used_trade.price IS '거래가(KRW) — 고정가 또는 낙찰가';
COMMENT ON COLUMN used_trade.shipping_fee IS '배송비(KRW) 스냅샷';
COMMENT ON COLUMN used_trade.fee_bp IS '수수료율(만분율) — 거래 시점 site_setting 스냅샷';
COMMENT ON COLUMN used_trade.fee_amount IS '플랫폼 수수료(KRW) = price × fee_bp / 10000 반올림';
