CREATE TABLE cart_item
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id UUID        NOT NULL,
    product_id BIGINT      NOT NULL,
    quantity   INT         NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE cart_item
    ADD CONSTRAINT cart_item_quantity_positive CHECK (quantity > 0);

CREATE UNIQUE INDEX cart_item_account_product_unique ON cart_item (account_id, product_id);
CREATE INDEX cart_item_product_idx ON cart_item (product_id);
CREATE INDEX cart_item_created_at_idx ON cart_item (created_at);
CREATE INDEX cart_item_updated_at_idx ON cart_item (updated_at);

COMMENT ON TABLE cart_item IS '장바구니 항목';
COMMENT ON COLUMN cart_item.id IS 'PK';
COMMENT ON COLUMN cart_item.account_id IS '회원 ID';
COMMENT ON COLUMN cart_item.product_id IS '상품 ID';
COMMENT ON COLUMN cart_item.quantity IS '수량';
COMMENT ON COLUMN cart_item.created_at IS '생성일';
COMMENT ON COLUMN cart_item.updated_at IS '수정일';

CREATE TABLE "order"
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no        TEXT        NOT NULL,
    account_id      UUID        NOT NULL,
    status          TEXT        NOT NULL,
    product_amount  INT         NOT NULL,
    discount_amount INT         NOT NULL,
    delivery_amount INT         NOT NULL,
    total_amount    INT         NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE "order"
    ADD CONSTRAINT order_amounts_non_negative
        CHECK (product_amount >= 0 AND discount_amount >= 0 AND delivery_amount >= 0 AND total_amount >= 0);

CREATE UNIQUE INDEX order_order_no_unique ON "order" (order_no);
CREATE INDEX order_account_created_at_idx ON "order" (account_id, created_at);
CREATE INDEX order_status_idx ON "order" (status);
CREATE INDEX order_created_at_idx ON "order" (created_at);
CREATE INDEX order_updated_at_idx ON "order" (updated_at);

COMMENT ON TABLE "order" IS '주문';
