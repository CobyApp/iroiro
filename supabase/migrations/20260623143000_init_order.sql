-- ============================================================================
-- GRANT — app 롤만. 주문 기록은 정정하지 않고 이력으로 쌓으므로 대부분 DELETE 미부여.
--   - cart_item : 유일한 DELETE 부여 — 담았다 빼는 게 정상 동작인 임시 데이터
--   - order_item·order_address·order_status_history : INSERT 후 불변(주문 시점 스냅샷·이력)
--   - order·payment : 상태 전이가 있어 UPDATE까지
--   - delivery_policy : 단일 행(id=1)을 이 마이그레이션이 심는다 → INSERT 미부여(2행 방지)
--   - order_no_seq : 날짜별 채번기(도메인 데이터 아님). Postgres 시퀀스로는 날짜별 리셋이
--       안 돼 테이블로 구현 — 채번 시 INSERT/UPDATE 필요, 삭제는 불필요
-- ============================================================================
REVOKE ALL ON cart_item, "order", order_item, order_address, payment, order_status_history,
    delivery_policy, order_no_seq
    FROM anon, authenticated, app;

GRANT SELECT, INSERT, UPDATE, DELETE ON cart_item TO app;
GRANT SELECT, INSERT, UPDATE ON "order" TO app;
GRANT SELECT, INSERT ON order_item TO app;
GRANT SELECT, INSERT ON order_address TO app;
GRANT SELECT, INSERT, UPDATE ON payment TO app;
GRANT SELECT, INSERT ON order_status_history TO app;
GRANT SELECT, UPDATE ON delivery_policy TO app;
GRANT SELECT, INSERT, UPDATE ON order_no_seq TO app;
