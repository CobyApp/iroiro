COMMENT ON COLUMN pending_post_photo.consumed_at IS '소비 시각';
COMMENT ON COLUMN pending_post_photo.created_at IS '생성일';
COMMENT ON COLUMN pending_post_photo.updated_at IS '수정일';

-- ============================================================================
-- GRANT — app 롤만. post·post_comment·post_photo는 DELETE 미부여(soft delete).
-- 신고는 컬럼 제한 UPDATE. pending_post_photo은 만료 행 정리 잡(후속)이 hard delete하므로 DELETE 부여.
-- ============================================================================
REVOKE ALL ON post, post_comment, post_report, post_comment_report, post_photo, pending_post_photo
    FROM anon, authenticated, app;
GRANT SELECT, INSERT, UPDATE ON post TO app;
GRANT SELECT, INSERT, UPDATE ON post_comment TO app;
GRANT SELECT, INSERT ON post_report TO app;
GRANT UPDATE (resolution, resolved_by, resolution_note, resolved_at, updated_at) ON post_report TO app;
GRANT SELECT, INSERT ON post_comment_report TO app;
GRANT UPDATE (resolution, resolved_by, resolution_note, resolved_at, updated_at) ON post_comment_report TO app;
GRANT SELECT, INSERT, UPDATE ON post_photo TO app;
GRANT SELECT, INSERT, UPDATE, DELETE ON pending_post_photo TO app;
