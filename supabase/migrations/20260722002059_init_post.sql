CREATE TABLE post
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    UUID        NOT NULL,
    public_code   TEXT        NOT NULL,
    topic         TEXT        NOT NULL,
    title         TEXT        NOT NULL,
    body          TEXT        NOT NULL,
    edited_at     TIMESTAMPTZ,
    hidden_at     TIMESTAMPTZ,
    hidden_reason TEXT,
    hidden_by     TEXT,
    deleted_at    TIMESTAMPTZ,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE post
    ADD CONSTRAINT post_hidden_consistency
        CHECK ((hidden_at IS NULL) = (hidden_reason IS NULL) AND (hidden_at IS NULL) = (hidden_by IS NULL));

CREATE UNIQUE INDEX post_public_code_unique ON post (public_code);
CREATE INDEX post_account_created_at_idx ON post (account_id, created_at);
CREATE INDEX post_created_at_idx ON post (created_at);
CREATE INDEX post_updated_at_idx ON post (updated_at);

COMMENT ON TABLE post IS '게시판 글';
COMMENT ON COLUMN post.id IS 'PK';
COMMENT ON COLUMN post.account_id IS '회원 ID';
COMMENT ON COLUMN post.public_code IS '공개 URL 코드';
COMMENT ON COLUMN post.topic IS '주제';
COMMENT ON COLUMN post.title IS '제목';
COMMENT ON COLUMN post.body IS '본문';
COMMENT ON COLUMN post.edited_at IS '콘텐츠 편집 시각';
COMMENT ON COLUMN post.hidden_at IS '숨김 시각';
COMMENT ON COLUMN post.hidden_reason IS '숨김 사유';
COMMENT ON COLUMN post.hidden_by IS '숨김 처리자';
COMMENT ON COLUMN post.deleted_at IS '삭제 시각';
COMMENT ON COLUMN post.created_at IS '생성일';
COMMENT ON COLUMN post.updated_at IS '수정일';

