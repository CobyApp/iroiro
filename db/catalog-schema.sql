    name        TEXT        NOT NULL,
    name_i18n   JSONB,
    debut_date  DATE,
    retire_date DATE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by  TEXT,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by  TEXT
);

CREATE INDEX IF NOT EXISTS member_name_idx ON member (name);
CREATE INDEX IF NOT EXISTS member_created_at_idx ON member (created_at);
CREATE INDEX IF NOT EXISTS member_updated_at_idx ON member (updated_at);

COMMENT ON TABLE member IS '멤버';
COMMENT ON COLUMN member.name IS '한국어 멤버명';
COMMENT ON COLUMN member.name_i18n IS '다국어 멤버명 — {"ja-jpan","ja-hira","en"}';
COMMENT ON COLUMN member.debut_date IS '데뷔일';
COMMENT ON COLUMN member.retire_date IS '은퇴일';

-- ── 팀-멤버 활동 이력 ─────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS team_member
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id           BIGINT      NOT NULL,
    member_id         BIGINT      NOT NULL,
    active_start_date DATE        NOT NULL,
    active_end_date   DATE,
    role              TEXT,
    display_order     INT,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by        TEXT,
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by        TEXT
);

CREATE UNIQUE INDEX IF NOT EXISTS team_member_active_member_team_unique ON team_member (member_id, team_id) WHERE active_end_date IS NULL;
CREATE INDEX IF NOT EXISTS team_member_active_idx ON team_member (team_id, member_id) WHERE active_end_date IS NULL;
CREATE INDEX IF NOT EXISTS team_member_team_order_idx ON team_member (team_id, display_order);
CREATE INDEX IF NOT EXISTS team_member_created_at_idx ON team_member (created_at);
CREATE INDEX IF NOT EXISTS team_member_updated_at_idx ON team_member (updated_at);

COMMENT ON TABLE team_member IS '팀-멤버 활동 이력';
COMMENT ON COLUMN team_member.active_start_date IS '활동 시작일';
COMMENT ON COLUMN team_member.active_end_date IS '활동 종료일(NULL 이면 현역)';
COMMENT ON COLUMN team_member.role IS '팀 내 역할';
COMMENT ON COLUMN team_member.display_order IS '그룹 내 공식 순번(1부터)';

