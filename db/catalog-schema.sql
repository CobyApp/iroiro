-- 앱 접속 롤 — LOGIN·비밀번호는 적용 스크립트가 별도로 부여한다(ALTER ROLE catalog_app WITH LOGIN PASSWORD ...).
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'catalog_app') THEN
        CREATE ROLE catalog_app NOLOGIN;
    END IF;
END
$$;

-- ── 그룹 ────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS team
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT        NOT NULL,
    name_i18n     JSONB,
    debut_date    DATE,
    disband_date  DATE,
    display_order INTEGER,
    theme_color   TEXT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by    TEXT,
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by    TEXT
);

CREATE INDEX IF NOT EXISTS team_name_idx ON team (name);
CREATE INDEX IF NOT EXISTS team_display_order_idx ON team (display_order);
CREATE INDEX IF NOT EXISTS team_created_at_idx ON team (created_at);
CREATE INDEX IF NOT EXISTS team_updated_at_idx ON team (updated_at);

COMMENT ON TABLE team IS '팀/그룹';
COMMENT ON COLUMN team.name IS '한국어 그룹명';
COMMENT ON COLUMN team.name_i18n IS '다국어 그룹명 — {"ja-jpan","ja-hira","en"}';
COMMENT ON COLUMN team.debut_date IS '데뷔일';
COMMENT ON COLUMN team.disband_date IS '해체일';
COMMENT ON COLUMN team.display_order IS '그룹 노출 순서(1부터, 관리자 지정). NULL 은 맨 뒤. 운영 규칙: CUTIE STREET 1, 나머지 데뷔순';
COMMENT ON COLUMN team.theme_color IS '그룹 고유색 — #rrggbb. NULL 이면 기본 색';

-- ── 멤버 ────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS member
