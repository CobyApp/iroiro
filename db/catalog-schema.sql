-- 이 파일은 커머스 DB(db/schema.sql)와 **다른 데이터베이스**(iroiro_catalog)에 적용한다.
-- 토레카 마스터(그룹·멤버·시리즈·종류·카드)는 환경마다 중복 저장할 이유가 없어 한곳에 두고,
-- dev·prd 앱이 CATALOG_DATABASE_URL 로 같은 DB에 접속한다(2026-09-22 결정).
--
-- 규칙은 db/schema.sql 과 동일(docs/architecture/data-modeling.md):
--  - 앱은 비특권 `catalog_app` 롤로 접속하고 GRANT 매트릭스가 DB 방어선이다(RLS 미사용).
--  - FK 없음(relationMode=prisma). 커머스 테이블(product·favorite·post…)은 여기 id 를 값으로만 참조한다.
--  - 변경은 아래에 `-- [timestamp_name]` 섹션으로 덧붙이고, 문장은 재실행 안전(IF NOT EXISTS)하게 쓴다.
--  - Prisma 정본은 이 파일. prisma/catalog.prisma 는 `npm run db:pull:catalog` 파생물.
--
-- 로컬: compose.yaml 의 postgres 에 `iroiro_catalog` DB 를 만들고(docker/initdb) `npm run db:reset` 이 적용.
-- 운영: 운영 RDS(iroiro-prd) 안의 별도 DB. 절차는 docs/deployment.md §카탈로그 DB.
