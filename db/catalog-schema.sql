-- ── 시리즈 ──────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS series
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku         TEXT        NOT NULL,
    team_id     BIGINT,
    kind        TEXT        NOT NULL,
    label       TEXT        NOT NULL,
    label_i18n  JSONB,
    product_url TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS series_sku_unique ON series (sku);
CREATE INDEX IF NOT EXISTS series_team_kind_idx ON series (team_id, kind);
CREATE INDEX IF NOT EXISTS series_created_at_idx ON series (created_at);

COMMENT ON TABLE series IS '시리즈 — 카드가 속하는 발매 단위(그룹→종류→시리즈)';
COMMENT ON COLUMN series.sku IS '시리즈 코드(예: CS-0225, usr-xxxx) — 유일';
COMMENT ON COLUMN series.team_id IS '소속 그룹 team.id (NULL 허용)';
COMMENT ON COLUMN series.kind IS '종류 — series_kind.key';
COMMENT ON COLUMN series.label IS '시리즈 이름 원문(대개 일본어)';
COMMENT ON COLUMN series.label_i18n IS '시리즈 이름 다국어 — {"ko": "…"} 한국어 병기';
COMMENT ON COLUMN series.product_url IS '공식 상품 페이지 URL(선택)';

-- ── 카드 ────────────────────────────────────────────────────────────────────
-- 토레카 마스터 — 판매물(product/used_listing)이 아닌 "카드 그 자체". 앞면 이미지 하나만 보관하며
-- 객체는 카탈로그 버킷(CATALOG_BUCKET)에 두 벌로 저장한다: cards/wm/<uuid>.jpg(공개·워터마크),
-- cards/clean/<uuid>.jpg(비공개·원본). front_r2_key 는 wm 키이고 clean 키는 규약으로 파생한다.
CREATE TABLE IF NOT EXISTS card
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_code               TEXT,
    item_type               TEXT        NOT NULL DEFAULT 'photocard',
    team_id                 BIGINT,
    member_id               BIGINT,
    series_id               BIGINT,
    name                    TEXT        NOT NULL,
    description             TEXT,
    front_r2_key            TEXT,
    retail_price_jpy        INTEGER     NOT NULL DEFAULT 0,
    pose                    INTEGER     NOT NULL DEFAULT 1,
    status                  TEXT        NOT NULL DEFAULT 'active',
    submitted_by_account_id UUID,
    submitted_env           TEXT,
    review_note             TEXT,
    analysis_embedding      JSONB,
    analysis_model          TEXT,
    analyzed_at             TIMESTAMPTZ,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT card_status_chk CHECK (status IN ('active', 'pending', 'rejected'))
);

CREATE INDEX IF NOT EXISTS card_team_member_idx ON card (team_id, member_id);
CREATE INDEX IF NOT EXISTS card_series_idx ON card (series_id);
CREATE INDEX IF NOT EXISTS card_status_idx ON card (status);
CREATE INDEX IF NOT EXISTS card_created_at_idx ON card (created_at);
CREATE INDEX IF NOT EXISTS card_analyzed_idx ON card (team_id, member_id) WHERE analyzed_at IS NOT NULL;

COMMENT ON TABLE card IS '토레카 마스터 (카드 원본 데이터) — dev·prd 공유';
COMMENT ON COLUMN card.item_code IS '아이템 코드(SKU 성격, 선택)';
COMMENT ON COLUMN card.item_type IS '아이템 종류 (photocard 등)';
COMMENT ON COLUMN card.name IS '카드 이름 — "멤버 · 시리즈" 규칙으로 자동 생성';
COMMENT ON COLUMN card.front_r2_key IS '앞면 워터마크 이미지 키(cards/wm/<uuid>.jpg). 원본은 cards/clean/<uuid>.jpg 로 파생';
COMMENT ON COLUMN card.retail_price_jpy IS '정가(엔)';
COMMENT ON COLUMN card.pose IS '포즈 번호 — 같은 (시리즈, 멤버) 내 1부터 순번';
COMMENT ON COLUMN card.status IS '상태 — active(공개)/pending(제보 검수 대기)/rejected(반려)';
COMMENT ON COLUMN card.submitted_by_account_id IS '제보한 회원 ID(제보 env 의 account.id) — NULL 이면 관리자 직접 등록';
COMMENT ON COLUMN card.submitted_env IS '제보가 들어온 환경(dev/prd/local) — 계정 id 는 환경별 DB 에 있으므로 같은 환경에서만 보상·표시';
COMMENT ON COLUMN card.review_note IS '검수 메모 (반려 사유 등)';
COMMENT ON COLUMN card.analysis_embedding IS '앞면(clean) 이미지 임베딩 벡터(JSONB float 배열, L2 정규화). 유사 카드 매칭용';
COMMENT ON COLUMN card.analysis_model IS '임베딩 생성 모델·버전 (예: amazon.titan-embed-image-v1)';
COMMENT ON COLUMN card.analyzed_at IS '이미지 분석 완료 시각. 미분석이면 NULL';

-- ── GRANT 매트릭스 — 앱 롤 catalog_app ──────────────────────────────────────
-- 카탈로그 공간의 관리자 CRUD + 유저 제보(card INSERT) + 등록 화면의 시리즈 즉석 추가(series INSERT).
GRANT USAGE ON SCHEMA public TO catalog_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON team, member, team_member, series, series_kind, card TO catalog_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO catalog_app;

