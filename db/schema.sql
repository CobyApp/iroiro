-- 기존 카드 백필 — (시리즈, 멤버)별 id 순서대로 1, 2, 3…
WITH ranked AS (
    SELECT id,
           ROW_NUMBER() OVER (
               PARTITION BY series_id, member_id
               ORDER BY id
           ) AS rn
    FROM card
)
UPDATE card
SET pose = ranked.rn
FROM ranked
WHERE card.id = ranked.id;

